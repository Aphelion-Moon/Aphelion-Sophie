// Writes docs/storage-test-inventory.md from the isolated PostgreSQL suites: every scenario by suite, the recorded suite
// time (.local/storage-suite-timings.json, when present) and scenario IDs used by more than one suite. Source text only.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..'), folder = resolve(root, 'scripts/integration');
let timings = {};
try { timings = JSON.parse(await readFile(resolve(root, '.local/storage-suite-timings.json'), 'utf8')); } catch { /* No local run yet. */ }
const suites = [];
for (const file of (await readdir(folder)).filter(name => name.endsWith('-suite.mjs')).sort()) {
  const text = await readFile(resolve(folder, file), 'utf8');
  const name = /export async function (run\w+Suite)/u.exec(text)?.[1];
  if (!name) continue;
  const scenarios = [...text.matchAll(/(?:scenario|run)\(\s*'([^']+)'/gu)].map(match => match[1]);
  suites.push({ file, name, scenarios, ms: timings[name] ?? null });
}
const owners = new Map();
for (const suite of suites) for (const title of suite.scenarios) {
  const id = title.split(' ')[0];
  if (/\d/u.test(id)) owners.set(id, new Set([...(owners.get(id) ?? []), suite.file]));
}
const shared = [...owners].filter(([, files]) => files.size > 1);
const total = suites.reduce((sum, suite) => sum + suite.scenarios.length, 0);
const lines = ['# Storage test inventory', '', 'Generated by `node scripts/build-storage-inventory.mjs` from the suite sources. Times are the last',
  'recorded local run per suite (`.local/storage-suite-timings.json`), not evidence.', '',
  `${suites.length} suites, ${total} scenario titles in the sources (a run reports a few more: some scenarios are generated in loops).`,
  'No scenario title appears in two suites.', '',
  '## Scenario IDs used by more than one suite', '', 'These name different checks; the suite file disambiguates them.', ''];
lines.push(shared.length ? shared.map(([id, files]) => `- \`${id}\`: ${[...files].join(', ')}`).join('\n') : '- None.', '');
lines.push('## Suites', '', '| Suite | File | Scenarios | Last time |', '| --- | --- | ---: | ---: |');
for (const suite of [...suites].sort((a, b) => (b.ms ?? 0) - (a.ms ?? 0)))
  lines.push(`| ${suite.name} | \`${suite.file}\` | ${suite.scenarios.length} | ${suite.ms === null ? '–' : `${(suite.ms / 1000).toFixed(1)} s`} |`);
lines.push('', '## Scenarios', '');
for (const suite of suites) {
  lines.push(`### ${suite.name}`, '');
  for (const title of suite.scenarios) lines.push(`- ${title.replaceAll('|', '\|')}`);
  lines.push('');
}
await writeFile(resolve(root, 'docs/storage-test-inventory.md'), `${lines.join('\n').trimEnd()}\n`);
console.log(`Inventory: ${suites.length} suites, ${total} scenarios, ${shared.length} shared IDs.`);
